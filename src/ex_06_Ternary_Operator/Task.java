package ex_06_Ternary_Operator;

public class Task {
    public static void main(String[] args) {

        int marks = 100;

        String result = (marks > 40) ? "Pass" : "Fail";

        System.out.println(result);

        int marks1 = 30;

        String result1 = (marks1 > 40) ? "Pass" : "Fail";

        System.out.println(result1);
    }
}
