package ex_02_Java_Basics;

public class Lab015_Variables {
    public static void main(String[] args) {

        // ```
        // data_type     variable_name = variable_value
        //````

        // Variable = Local Variable, Static Variable, Instance Variable

        byte age_nikhil = 35;

        //byte --> data type - type of container
        //age_nikhil --> variable_name | identifier
        //= --> Assignment Operator
        // 35 --> variable_value | Literal

        age_nikhil = 65;
        age_nikhil = 69;
        System.out.println(age_nikhil);

    }
}
